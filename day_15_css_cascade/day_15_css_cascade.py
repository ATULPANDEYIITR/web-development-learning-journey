# ---------------------------------------------------------------------------
# 17. A custom-property resolver
# ---------------------------------------------------------------------------

CUSTOM_PROPERTY_PATTERN = re.compile(
    r"var\(\s*(--[A-Za-z0-9_-]+)"
    r"(?:\s*,\s*([^()]+))?\s*\)"
)


def collect_custom_properties(
    engine: CSSCascadeEngine,
    element: Element,
) -> Dict[str, str]:
    """
    Collect custom properties visible to an element.

    Custom properties inherit by default, which makes them useful for
    component-level theming.
    """
    result: Dict[str, str] = {}

    if element.parent is not None:
        result.update(
            collect_custom_properties(engine, element.parent)
        )

    for rule in engine.rules:
        if selector_matches(element, rule.selector):
            for declaration in rule.declarations:
                if declaration.property_name.startswith("--"):
                    result[declaration.property_name] = declaration.value

    for name, value in element.inline_styles.items():
        if name.startswith("--"):
            result[name] = value

    return result


def resolve_custom_properties(
    value: str,
    custom_properties: Dict[str, str],
    max_depth: int = 20,
) -> str:
    """
    Resolve simple var() expressions.

    A browser performs more sophisticated token-level processing. This helper
    exists to demonstrate the conceptual relationship between custom
    properties and the cascade.
    """

    result = value

    for _ in range(max_depth):
        match = CUSTOM_PROPERTY_PATTERN.search(result)

        if not match:
            return result

        name = match.group(1)
        fallback = match.group(2)

        if name in custom_properties:
            replacement = custom_properties[name]
        elif fallback is not None:
            replacement = fallback.strip()
        else:
            raise ValueError(
                f"Undefined custom property: {name}"
            )

        result = result[:match.start()] + replacement + result[match.end():]

    raise ValueError("Too many nested var() references")


