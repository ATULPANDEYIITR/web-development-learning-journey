# 5. CSS-wide keywords and inheritance
# ---------------------------------------------------------------------------

INHERITED_PROPERTIES = {
    "color",
    "font-family",
    "font-size",
    "font-weight",
    "line-height",
    "text-align",
    "visibility",
    "cursor",
}

INITIAL_VALUES = {
    "color": "black",
    "background-color": "transparent",
    "font-size": "medium",
    "font-weight": "normal",
    "display": "inline",
    "margin": "0",
    "padding": "0",
    "border": "none",
    "opacity": "1",
}


def is_inherited_property(property_name: str) -> bool:
    return property_name.lower() in INHERITED_PROPERTIES


# ---------------------------------------------------------------------------
# 6. Cascade engine
# ---------------------------------------------------------------------------

class CSSCascadeEngine:
    def __init__(self, rules: List[Rule]):
        self.rules = rules

    def declarations_for(
        self,
        element: Element,
        property_name: str,
    ) -> List[CSSDeclaration]:
        candidates: List[CSSDeclaration] = []

        for rule in self.rules:
            if not selector_matches(element, rule.selector):
                continue

            for declaration in rule.declarations:
                if declaration.property_name == property_name:
                    candidates.append(declaration)

        # Inline styles are represented as an author declaration with an
        # extremely strong specificity component.
        if property_name in element.inline_styles:
            raw_value = element.inline_styles[property_name]
            important = raw_value.strip().endswith("!important")

            if important:
                raw_value = raw_value.replace("!important", "").strip()

            candidates.append(
                CSSDeclaration(
                    property_name=property_name,
                    value=raw_value,
                    important=important,
                    source_order=10_000_000,
                    origin="author",
                    selector="style attribute",
                    specificity=(1, 0, 0),
                )
            )

        return candidates

    def resolve(
        self,
        element: Element,
        property_name: str,
        trace: bool = False,
    ) -> Tuple[str, List[Candidate]]:
        candidates = self.declarations_for(element, property_name)

        candidate_records: List[Candidate] = []

        for declaration in candidates:
            candidate_records.append(
                Candidate(
                    declaration=declaration,
                    matched=True,
                    reason="Selector matched the element.",
                )
            )

        if candidates:
            winner = max(
                candidates,
                key=lambda declaration: declaration.priority_key()
            )

            value = winner.value.strip()

            # CSS-wide keywords.
            if value == "inherit":
                if element.parent:
                    inherited_value, _ = self.resolve(
                        element.parent,
                        property_name,
                        trace=False,
                    )
                    return inherited_value, candidate_records
                return INITIAL_VALUES.get(property_name, "initial"), candidate_records

            if value == "initial":
                return INITIAL_VALUES.get(property_name, "initial"), candidate_records

            if value == "unset":
                if is_inherited_property(property_name) and element.parent:
                    inherited_value, _ = self.resolve(
                        element.parent,
                        property_name,
                        trace=False,
                    )
                    return inherited_value, candidate_records
                return INITIAL_VALUES.get(property_name, "initial"), candidate_records

            if value == "revert":
                # A complete browser implementation would revert to the
                # previous cascade origin/layer. We model it as initial here.
                return INITIAL_VALUES.get(property_name, "initial"), candidate_records

            return value, candidate_records

        # No declaration won. Inherited properties look to the parent.
        if is_inherited_property(property_name) and element.parent:
            inherited_value, _ = self.resolve(
                element.parent,
                property_name,
                trace=False,
            )
            return inherited_value, candidate_records

        return INITIAL_VALUES.get(property_name, "initial"), candidate_records

    def explain(
        self,
        element: Element,
        property_name: str,
    ) -> None:
        value, candidates = self.resolve(
            element,
            property_name,
            trace=True,
        )

        print(f"\nProperty: {property_name}")
        print(f"Element:  {element.description()}")
        print(f"Final:    {value}")

        if not candidates:
            if is_inherited_property(property_name) and element.parent:
                print("Reason:   No local declaration; value comes through inheritance.")
            else:
                print("Reason:   No matching declaration; initial value is used.")
            return

        print("\nCascade candidates:")

        ordered = sorted(
            candidates,
            key=lambda candidate: candidate.declaration.priority_key(),
            reverse=True,
        )

        for index, candidate in enumerate(ordered):
            declaration = candidate.declaration

            status = "WINNER" if index == 0 else "loser"

            print(
                f"  {status:7} "
                f"{declaration.selector:20} "
                f"{declaration.property_name}: "
                f"{declaration.value}"
                f"{' !important' if declaration.important else ''} "
                f"specificity={declaration.specificity} "
                f"order={declaration.source_order}"
            )


# ---------------------------------------------------------------------------
# 7. Rule construction helper
# ---------------------------------------------------------------------------

def make_rule(
    selector: str,
    declarations: Dict[str, str],
    source_order: int,
) -> Rule:
    specificity = calculate_specificity(selector)

    css_declarations = []

    for property_name, raw_value in declarations.items():
        value = raw_value.strip()

        important = False

        if value.endswith("!important"):
            important = True
            value = value[:-10].strip()

        css_declarations.append(
            CSSDeclaration(
                property_name=property_name,
                value=value,
                important=important,
                source_order=source_order,
                selector=selector,
                specificity=specificity,
            )
        )

    return Rule(
        selector=selector,
        declarations=css_declarations,
        source_order=source_order,
    )


