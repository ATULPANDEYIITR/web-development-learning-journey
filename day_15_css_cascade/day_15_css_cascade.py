"""
CSS Cascade: Cascade, Inheritance, Specificity, Source Order, !important,
and Debugging Styles

This standalone study script teaches the CSS cascade from beginner to advanced
level by implementing a small CSS cascade engine in Python.

The program does not require external packages. It models:
- CSS declarations
- selectors
- specificity
- source order
- inheritance
- !important
- inline styles
- CSS-wide keywords
- custom properties
- debugging and explanation of winning declarations
- performance considerations
- realistic component styling

The implementation is intentionally simplified compared with a browser's full
CSS engine. A real browser also considers origins, layers, pseudo-elements,
pseudo-classes, media queries, container queries, animations, transitions,
shadow DOM, and property-specific inheritance behavior.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Dict, List, Optional, Tuple
import re


# ---------------------------------------------------------------------------
# 1. Fundamental terminology
# ---------------------------------------------------------------------------
#
# CSS declaration:
#     color: blue;
#
# Property:
#     color
#
# Value:
#     blue
#
# Rule:
#     .button { color: blue; }
#
# Selector:
#     .button
#
# Specificity:
#     A tuple describing how strongly a selector targets an element.
#
# Cascade:
#     The browser's process for deciding which applicable declaration wins
#     when multiple declarations target the same property.
#
# Inheritance:
#     The mechanism by which some properties obtain their value from an
#     ancestor when the element does not establish its own value.
#
# Source order:
#     When otherwise relevant cascade factors tie, the later declaration wins.
#
# !important:
#     Changes the cascade priority of a declaration. It should be used
#     sparingly because it makes normal overrides more difficult.


# ---------------------------------------------------------------------------
# 2. Data structures
# ---------------------------------------------------------------------------

@dataclass
class Element:
    tag: str
    element_id: Optional[str] = None
    classes: List[str] = field(default_factory=list)
    attributes: Dict[str, str] = field(default_factory=dict)
    parent: Optional["Element"] = None
    children: List["Element"] = field(default_factory=list)
    inline_styles: Dict[str, str] = field(default_factory=dict)

    def add_child(self, child: "Element") -> None:
        child.parent = self
        self.children.append(child)

    def description(self) -> str:
        result = self.tag
        if self.element_id:
            result += f"#{self.element_id}"
        for class_name in self.classes:
            result += f".{class_name}"
        return result


@dataclass
class CSSDeclaration:
    property_name: str
    value: str
    important: bool = False
    source_order: int = 0
    origin: str = "author"
    selector: str = ""
    specificity: Tuple[int, int, int] = (0, 0, 0)

    def priority_key(self) -> Tuple[int, int, int, int, int, int, int]:
        """
        A teaching-oriented cascade key.

        The real CSS cascade has more dimensions than this simplified model.
        Here we compare:
        1. importance
        2. origin
        3. specificity
        4. source order

        Inline styles receive a separate specificity-like treatment when
        generated by the resolver.
        """
        importance_rank = 1 if self.important else 0

        origin_rank = {
            "user-agent": 0,
            "user": 1,
            "author": 2,
        }.get(self.origin, 2)

        a, b, c = self.specificity

        return (
            importance_rank,
            origin_rank,
            a,
            b,
            c,
            self.source_order,
            0,
        )


@dataclass
class Rule:
    selector: str
    declarations: List[CSSDeclaration]
    source_order: int


@dataclass
class Candidate:
    declaration: CSSDeclaration
    matched: bool
    reason: str


# ---------------------------------------------------------------------------
# 3. Specificity
# ---------------------------------------------------------------------------

def calculate_specificity(selector: str) -> Tuple[int, int, int]:
    """
    Calculate simplified CSS specificity.

    Specificity is commonly represented as:

        (ID, class/attribute/pseudo-class, type/pseudo-element)

    Examples:
        p             -> (0, 0, 1)
        .card         -> (0, 1, 0)
        #main         -> (1, 0, 0)
        #main .card p -> (1, 1, 1)

    This function intentionally does not implement every modern selector
    exception such as :where(), :is(), :not(), nesting, or selector lists.
    """

    selector_without_strings = re.sub(r'"[^"]*"|\'[^\']*\'', "", selector)

    ids = len(re.findall(r"#[A-Za-z_][\w-]*", selector_without_strings))

    classes = len(re.findall(r"\.[A-Za-z_][\w-]*", selector_without_strings))

    attributes = len(
        re.findall(r"\[[^\]]+\]", selector_without_strings)
    )

    pseudo_classes = len(
        re.findall(
            r":(?!:)[A-Za-z_-][\w-]*(?:\([^)]*\))?",
            selector_without_strings,
        )
    )

    pseudo_elements = len(
        re.findall(r"::[A-Za-z_-][\w-]*", selector_without_strings)
    )

    # Remove IDs, classes, attributes, pseudo selectors and universal
    # selectors before estimating type-selector count.
    simplified = re.sub(
        r"#[A-Za-z_][\w-]*"
        r"|\.[A-Za-z_][\w-]*"
        r"\[[^\]]+\]"
        r"|::?[A-Za-z_-][\w-]*(?:\([^)]*\))?",
        " ",
        selector_without_strings,
    )

    type_names = re.findall(
        r"(?<![-\w])[A-Za-z][A-Za-z0-9_-]*", simplified
    )

    # Common combinators and CSS keywords are not type selectors.
    ignored = {
        "and",
        "or",
        "not",
        "where",
        "is",
    }

    type_count = sum(
        1 for name in type_names if name.lower() not in ignored
    )

    type_count += pseudo_elements

    return (
        ids,
        classes + attributes + pseudo_classes,
        type_count,
    )


# ---------------------------------------------------------------------------
# 4. Selector matching
# ---------------------------------------------------------------------------

def simple_selector_matches(element: Element, selector: str) -> bool:
    """
    Match a basic compound selector.

    Supported examples:
        div
        .card
        #main
        div.card
        div#main.card
        [data-state="active"]
        [data-state]

    The implementation is deliberately educational rather than a complete
    CSS selector engine.
    """

    selector = selector.strip()

    if not selector:
        return False

    if ":" in selector:
        # Pseudo-classes are outside this small matching engine.
        selector = selector.split(":", 1)[0]

    selector = selector.replace("::before", "").strip()

    if not selector:
        return True

    tag_match = re.match(r"^[A-Za-z][A-Za-z0-9_-]*|\*", selector)

    if tag_match:
        tag = tag_match.group(0)
        if tag != "*" and element.tag.lower() != tag.lower():
            return False

    for element_id in re.findall(r"#([A-Za-z_][\w-]*)", selector):
        if element.element_id != element_id:
            return False

    for class_name in re.findall(r"\.([A-Za-z_][\w-]*)", selector):
        if class_name not in element.classes:
            return False

    for attribute_expression in re.findall(
        r"\[([^\]]+)\]", selector
    ):
        expression = attribute_expression.strip()

        if "=" in expression:
            attribute_name, expected = expression.split("=", 1)
            attribute_name = attribute_name.strip()
            expected = expected.strip().strip("\"'")
            if element.attributes.get(attribute_name) != expected:
                return False
        else:
            if expression not in element.attributes:
                return False

    return True


def selector_matches(element: Element, selector: str) -> bool:
    """
    Support basic descendant and child combinators.

    Examples:
        .card .title
        .card > .title
        main .button

    This is enough to demonstrate why a declaration may or may not participate
    in the cascade.
    """

    selector = selector.strip()

    if ">" in selector:
        left, right = selector.rsplit(">", 1)
        if not simple_selector_matches(element, right.strip()):
            return False

        if element.parent is None:
            return False

        return selector_matches(element.parent, left.strip())

    parts = selector.split()

    if len(parts) == 1:
        return simple_selector_matches(element, parts[0])

    if not simple_selector_matches(element, parts[-1]):
        return False

    ancestor = element.parent

    for part in reversed(parts[:-1]):
        found = False

        while ancestor is not None:
            if simple_selector_matches(ancestor, part):
                found = True
                ancestor = ancestor.parent
                break
            ancestor = ancestor.parent

        if not found:
            return False

    return True


