def assert_equal(actual, expected, description):
    if actual != expected:
        raise AssertionError(
            f"{description}: expected {expected!r}, got {actual!r}"
        )


def run_tests() -> None:
    print("\n" + "=" * 72)
    print("TESTS")
    print("=" * 72)

    # Equal specificity: later wins.
    rules = [
        make_rule(".box", {"color": "red"}, 1),
        make_rule(".box", {"color": "blue"}, 2),
    ]
    element = Element(tag="div", classes=["box"])
    engine = CSSCascadeEngine(rules)
    assert_equal(
        engine.resolve(element, "color")[0],
        "blue",
        "Source order",
    )

    # Specificity beats source order.
    rules = [
        make_rule(".box", {"color": "red"}, 1),
        make_rule("div.box", {"color": "blue"}, 2),
    ]
    engine = CSSCascadeEngine(rules)
    assert_equal(
        engine.resolve(element, "color")[0],
        "blue",
        "Specificity",
    )

    # Important declaration beats normal declaration.
    rules = [
        make_rule("#main .box", {"color": "red"}, 2),
        make_rule(".box", {"color": "green !important"}, 1),
    ]

    main = Element(tag="div", element_id="main")
    main.add_child(element)

    engine = CSSCascadeEngine(rules)

    assert_equal(
        engine.resolve(element, "color")[0],
        "green",
        "!important",
    )

    # Inheritance.
    parent = Element(tag="div")
    child = Element(tag="span")
    parent.add_child(child)

    rules = [
        make_rule("div", {"color": "purple"}, 1),
    ]

    engine = CSSCascadeEngine(rules)

    assert_equal(
        engine.resolve(child, "color")[0],
        "purple",
        "Inheritance",
    )

    print("All tests passed.")


