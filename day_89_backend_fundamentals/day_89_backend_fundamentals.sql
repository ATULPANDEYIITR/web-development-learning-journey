-- ---------------------------------------------------------
-- 3. Users
-- ---------------------------------------------------------

CREATE TABLE IF NOT EXISTS users (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    username VARCHAR(80) NOT NULL UNIQUE,

    email VARCHAR(255) NOT NULL UNIQUE,

    password_hash TEXT NOT NULL,

    is_active BOOLEAN NOT NULL DEFAULT TRUE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT username_not_blank
        CHECK (LENGTH(TRIM(username)) > 0),

    CONSTRAINT email_not_blank
        CHECK (LENGTH(TRIM(email)) > 0),

    CONSTRAINT password_hash_not_blank
        CHECK (LENGTH(TRIM(password_hash)) > 0)
);

-- ---------------------------------------------------------
-- 4. Projects
-- ---------------------------------------------------------

CREATE TABLE IF NOT EXISTS projects (
    project_id BIGINT GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    project_name VARCHAR(150) NOT NULL,

    description TEXT NOT NULL DEFAULT '',

    owner_id BIGINT NOT NULL,

    status project_status NOT NULL DEFAULT 'active',

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT project_owner_fk
        FOREIGN KEY (owner_id)
        REFERENCES users(user_id)
        ON DELETE RESTRICT,

    CONSTRAINT project_name_not_blank
        CHECK (LENGTH(TRIM(project_name)) > 0),

    CONSTRAINT project_description_length
        CHECK (LENGTH(description) <= 5000)
);

-- ---------------------------------------------------------
-- 5. Project membership
-- ---------------------------------------------------------

CREATE TABLE IF NOT EXISTS project_members (
    project_id BIGINT NOT NULL,

    user_id BIGINT NOT NULL,

    member_role VARCHAR(30) NOT NULL DEFAULT 'member',

    joined_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    PRIMARY KEY (project_id, user_id),

    CONSTRAINT project_member_project_fk
        FOREIGN KEY (project_id)
        REFERENCES projects(project_id)
        ON DELETE CASCADE,

    CONSTRAINT project_member_user_fk
        FOREIGN KEY (user_id)
        REFERENCES users(user_id)
        ON DELETE RESTRICT,

    CONSTRAINT valid_member_role
        CHECK (
            member_role IN (
                'owner',
                'admin',
                'member',
                'viewer'
            )
        )
);

-- ---------------------------------------------------------
-- 6. Tasks
-- ---------------------------------------------------------

CREATE TABLE IF NOT EXISTS tasks (
    task_id BIGINT GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    project_id BIGINT NOT NULL,

    assigned_to BIGINT,

    created_by BIGINT NOT NULL,

    title VARCHAR(150) NOT NULL,

    description TEXT NOT NULL DEFAULT '',

    status task_status NOT NULL DEFAULT 'pending',

    priority SMALLINT NOT NULL DEFAULT 3,

    version INTEGER NOT NULL DEFAULT 1,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    completed_at TIMESTAMPTZ,

    CONSTRAINT task_project_fk
        FOREIGN KEY (project_id)
        REFERENCES projects(project_id)
        ON DELETE CASCADE,

    CONSTRAINT task_assignee_fk
        FOREIGN KEY (assigned_to)
        REFERENCES users(user_id)
        ON DELETE SET NULL,

    CONSTRAINT task_creator_fk
        FOREIGN KEY (created_by)
        REFERENCES users(user_id)
        ON DELETE RESTRICT,

    CONSTRAINT task_title_not_blank
        CHECK (LENGTH(TRIM(title)) > 0),

    CONSTRAINT task_description_length
        CHECK (LENGTH(description) <= 2000),

    CONSTRAINT task_priority_range
        CHECK (priority BETWEEN 1 AND 5),

    CONSTRAINT task_version_positive
        CHECK (version > 0),

    CONSTRAINT task_completion_consistency
        CHECK (
            (status = 'completed' AND completed_at IS NOT NULL)
            OR
            (status <> 'completed' AND completed_at IS NULL)
        )
);

-- ---------------------------------------------------------
-- 7. API route registry
-- ---------------------------------------------------------

CREATE TABLE IF NOT EXISTS api_routes (
    route_id BIGINT GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    route_path VARCHAR(255) NOT NULL,

    http_method VARCHAR(10) NOT NULL,

    controller_name VARCHAR(100) NOT NULL,

    service_name VARCHAR(100) NOT NULL,

    requires_authentication BOOLEAN NOT NULL DEFAULT TRUE,

    is_enabled BOOLEAN NOT NULL DEFAULT TRUE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT unique_api_route
        UNIQUE (route_path, http_method),

    CONSTRAINT valid_http_method
        CHECK (
            http_method IN (
                'GET',
                'POST',
                'PUT',
                'PATCH',
                'DELETE'
            )
        )
);

-- ---------------------------------------------------------
-- 8. API request audit log
-- ---------------------------------------------------------

CREATE TABLE IF NOT EXISTS api_request_logs (
    log_id BIGINT GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    request_id UUID NOT NULL UNIQUE,

    user_id BIGINT,

    route_id BIGINT,

    http_method VARCHAR(10) NOT NULL,

    request_path TEXT NOT NULL,

    response_status SMALLINT,

    duration_ms NUMERIC(12, 3),

    error_code VARCHAR(80),

    requested_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT request_user_fk
        FOREIGN KEY (user_id)
        REFERENCES users(user_id)
        ON DELETE SET NULL,

    CONSTRAINT request_route_fk
        FOREIGN KEY (route_id)
        REFERENCES api_routes(route_id)
        ON DELETE SET NULL,

    CONSTRAINT valid_response_status
        CHECK (
            response_status IS NULL
            OR response_status BETWEEN 100 AND 599
        ),

    CONSTRAINT valid_duration
        CHECK (
            duration_ms IS NULL
            OR duration_ms >= 0
        )
);

