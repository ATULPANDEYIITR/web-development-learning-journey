-- ---------------------------------------------------------
-- 10. Updated timestamp trigger function
-- ---------------------------------------------------------

CREATE OR REPLACE FUNCTION update_modified_timestamp()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at := NOW();

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_projects_updated_at
ON projects;

CREATE TRIGGER trg_projects_updated_at
BEFORE UPDATE ON projects
FOR EACH ROW
EXECUTE FUNCTION update_modified_timestamp();

DROP TRIGGER IF EXISTS trg_tasks_updated_at
ON tasks;

CREATE TRIGGER trg_tasks_updated_at
BEFORE UPDATE ON tasks
FOR EACH ROW
EXECUTE FUNCTION update_modified_timestamp();

-- ---------------------------------------------------------
-- 11. Task state consistency trigger
-- ---------------------------------------------------------

CREATE OR REPLACE FUNCTION maintain_task_completion()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.status = 'completed' THEN
        IF OLD.status IS DISTINCT FROM NEW.status
           OR NEW.completed_at IS NULL THEN
            NEW.completed_at := NOW();
        END IF;
    ELSE
        NEW.completed_at := NULL;
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_task_completion
ON tasks;

CREATE TRIGGER trg_task_completion
BEFORE INSERT OR UPDATE OF status, completed_at
ON tasks
FOR EACH ROW
EXECUTE FUNCTION maintain_task_completion();

-- ---------------------------------------------------------
-- 12. Membership validation trigger
-- ---------------------------------------------------------

CREATE OR REPLACE FUNCTION validate_task_membership()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.assigned_to IS NOT NULL
       AND NOT EXISTS (
            SELECT 1
            FROM project_members pm
            WHERE pm.project_id = NEW.project_id
              AND pm.user_id = NEW.assigned_to
       ) THEN

        RAISE EXCEPTION
            'Assigned user % is not a member of project %',
            NEW.assigned_to,
            NEW.project_id
            USING ERRCODE = '23514';
    END IF;

    IF NOT EXISTS (
        SELECT 1
        FROM project_members pm
        WHERE pm.project_id = NEW.project_id
          AND pm.user_id = NEW.created_by
          AND pm.member_role IN ('owner', 'admin', 'member')
    ) THEN

        RAISE EXCEPTION
            'Task creator must have an authorized project membership'
            USING ERRCODE = '23514';
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_validate_task_membership
ON tasks;

CREATE TRIGGER trg_validate_task_membership
BEFORE INSERT OR UPDATE OF project_id, assigned_to, created_by
ON tasks
FOR EACH ROW
EXECUTE FUNCTION validate_task_membership();

-- ---------------------------------------------------------
-- 13. Create task function
-- ---------------------------------------------------------

CREATE OR REPLACE FUNCTION create_task(
    p_project_id BIGINT,
    p_created_by BIGINT,
    p_title VARCHAR(150),
    p_description TEXT DEFAULT '',
    p_assigned_to BIGINT DEFAULT NULL,
    p_priority SMALLINT DEFAULT 3
)
RETURNS BIGINT
LANGUAGE plpgsql
AS $$
DECLARE
    v_task_id BIGINT;
BEGIN
    IF p_title IS NULL OR LENGTH(TRIM(p_title)) = 0 THEN
        RAISE EXCEPTION 'Task title is required'
            USING ERRCODE = '22023';
    END IF;

    IF LENGTH(p_title) > 150 THEN
        RAISE EXCEPTION 'Task title exceeds 150 characters'
            USING ERRCODE = '22023';
    END IF;

    IF p_priority NOT BETWEEN 1 AND 5 THEN
        RAISE EXCEPTION 'Priority must be between 1 and 5'
            USING ERRCODE = '22023';
    END IF;

    INSERT INTO tasks (
        project_id,
        created_by,
        assigned_to,
        title,
        description,
        priority
    )
    VALUES (
        p_project_id,
        p_created_by,
        p_assigned_to,
        TRIM(p_title),
        COALESCE(p_description, ''),
        p_priority
    )
    RETURNING task_id INTO v_task_id;

    RETURN v_task_id;
END;
$$;

-- ---------------------------------------------------------
-- 14. Update task function with optimistic locking
-- ---------------------------------------------------------

CREATE OR REPLACE FUNCTION update_task(
    p_task_id BIGINT,
    p_expected_version INTEGER,
    p_title VARCHAR(150) DEFAULT NULL,
    p_description TEXT DEFAULT NULL,
    p_status task_status DEFAULT NULL
)
RETURNS tasks
LANGUAGE plpgsql
AS $$
DECLARE
    v_task tasks%ROWTYPE;
BEGIN
    IF p_title IS NOT NULL AND (
        LENGTH(TRIM(p_title)) = 0
        OR LENGTH(p_title) > 150
    ) THEN
        RAISE EXCEPTION 'Invalid task title'
            USING ERRCODE = '22023';
    END IF;

    IF p_description IS NOT NULL
       AND LENGTH(p_description) > 2000 THEN
        RAISE EXCEPTION 'Description exceeds maximum length'
            USING ERRCODE = '22023';
    END IF;

    UPDATE tasks
    SET
        title = COALESCE(p_title, title),
        description = COALESCE(p_description, description),
        status = COALESCE(p_status, status),
        version = version + 1
    WHERE task_id = p_task_id
      AND version = p_expected_version
    RETURNING * INTO v_task;

    IF NOT FOUND THEN
        IF EXISTS (
            SELECT 1
            FROM tasks
            WHERE task_id = p_task_id
        ) THEN
            RAISE EXCEPTION
                'Concurrent modification detected for task %',
                p_task_id
                USING ERRCODE = '40001';
        END IF;

        RAISE EXCEPTION
            'Task % does not exist',
            p_task_id
            USING ERRCODE = 'P0002';
    END IF;

    RETURN v_task;
END;
$$;

-- ---------------------------------------------------------
-- 15. Procedure for completing tasks
-- ---------------------------------------------------------

CREATE OR REPLACE PROCEDURE complete_task(
    p_task_id BIGINT
)
LANGUAGE plpgsql
AS $$
BEGIN
    UPDATE tasks
    SET status = 'completed'
    WHERE task_id = p_task_id;

    IF NOT FOUND THEN
        RAISE EXCEPTION
            'Task % does not exist',
            p_task_id;
    END IF;
END;
$$;

-- ---------------------------------------------------------
-- 16. Project task reporting view
-- ---------------------------------------------------------

CREATE OR REPLACE VIEW project_task_summary AS
SELECT
    p.project_id,
    p.project_name,
    p.status AS project_status,
    COUNT(t.task_id) AS total_tasks,

    COUNT(t.task_id) FILTER (
        WHERE t.status = 'pending'
    ) AS pending_tasks,

    COUNT(t.task_id) FILTER (
        WHERE t.status = 'in_progress'
    ) AS in_progress_tasks,

    COUNT(t.task_id) FILTER (
        WHERE t.status = 'completed'
    ) AS completed_tasks,

    ROUND(
        100.0 * COUNT(t.task_id) FILTER (
            WHERE t.status = 'completed'
        ) / NULLIF(COUNT(t.task_id), 0),
        2
    ) AS completion_percentage

FROM projects p

LEFT JOIN tasks t
    ON t.project_id = p.project_id

GROUP BY
    p.project_id,
    p.project_name,
    p.status;

-- ---------------------------------------------------------
-- 17. API route performance view
-- ---------------------------------------------------------

CREATE OR REPLACE VIEW api_route_performance AS
SELECT
    http_method,
    request_path,

    COUNT(*) AS total_requests,

    COUNT(*) FILTER (
        WHERE response_status BETWEEN 200 AND 299
    ) AS successful_requests,

    COUNT(*) FILTER (
        WHERE response_status BETWEEN 400 AND 499
    ) AS client_errors,

    COUNT(*) FILTER (
        WHERE response_status BETWEEN 500 AND 599
    ) AS server_errors,

    ROUND(
        AVG(duration_ms),
        2
    ) AS average_duration_ms,

    MAX(duration_ms) AS maximum_duration_ms

FROM api_request_logs

GROUP BY
    http_method,
    request_path;

