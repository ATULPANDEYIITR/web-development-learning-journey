-- 28. Evaluation: API error rate
-- ---------------------------------------------------------

SELECT
    request_path,

    COUNT(*) AS total_requests,

    COUNT(*) FILTER (
        WHERE response_status >= 400
    ) AS failed_requests,

    ROUND(
        100.0 * COUNT(*) FILTER (
