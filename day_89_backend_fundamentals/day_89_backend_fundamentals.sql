-- Retrieve all tasks for a project.

SELECT
    t.task_id,
    t.title,
    t.status,
    t.priority,
    u.username AS assigned_user,
    t.created_at,
    t.updated_at
FROM tasks t
LEFT JOIN users u
    ON u.user_id = t.assigned_to
WHERE t.project_id = 1
ORDER BY t.priority, t.created_at DESC;

-- Retrieve a single task.

SELECT *
FROM tasks
WHERE task_id = 2;

-- ---------------------------------------------------------
-- 25. CTE: task workload by user
-- ---------------------------------------------------------

WITH user_workload AS (
    SELECT
        u.user_id,
        u.username,

        COUNT(t.task_id) AS assigned_tasks,

        COUNT(t.task_id) FILTER (
            WHERE t.status = 'completed'
        ) AS completed_tasks

    FROM users u

    LEFT JOIN tasks t
        ON t.assigned_to = u.user_id

    GROUP BY
        u.user_id,
        u.username
)

SELECT
    username,
    assigned_tasks,
    completed_tasks,

    assigned_tasks - completed_tasks AS outstanding_tasks

FROM user_workload
ORDER BY outstanding_tasks DESC;

