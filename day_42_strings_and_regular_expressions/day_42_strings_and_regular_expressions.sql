-- PostgreSQL 15+
-- Repository governance model for pull requests, code review, approvals,
-- and protected-branch merge eligibility.

BEGIN;

CREATE SCHEMA IF NOT EXISTS repository_governance;
SET search_path TO repository_governance, public;

CREATE TABLE repositories (
    repository_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_name TEXT NOT NULL,
    repository_name TEXT NOT NULL,
    default_branch TEXT NOT NULL DEFAULT 'main',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (owner_name, repository_name),
    CHECK (owner_name <> ''),
    CHECK (repository_name <> ''),
    CHECK (default_branch <> '')
);

CREATE TABLE repository_users (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT NOT NULL UNIQUE,
    display_name TEXT NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    CHECK (username ~ '^[A-Za-z][A-Za-z0-9-]{2,38}$'),
    CHECK (display_name <> '')
);

CREATE TABLE branches (
    branch_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repository_id BIGINT NOT NULL REFERENCES repositories(repository_id)
        ON DELETE CASCADE,
    branch_name TEXT NOT NULL,
    head_sha TEXT NOT NULL,
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (repository_id, branch_name),
    CHECK (branch_name <> ''),
    CHECK (head_sha ~ '^[a-f0-9]{7,40}$')
);

CREATE TABLE commits (
    commit_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repository_id BIGINT NOT NULL REFERENCES repositories(repository_id)
        ON DELETE CASCADE,
    sha TEXT NOT NULL,
    author_id BIGINT NOT NULL REFERENCES repository_users(user_id),
    committed_at TIMESTAMPTZ NOT NULL,
    message TEXT NOT NULL,
    is_merge_commit BOOLEAN NOT NULL DEFAULT FALSE,
    UNIQUE (repository_id, sha),
    CHECK (sha ~ '^[a-f0-9]{7,40}$'),
    CHECK (message <> '')
);

CREATE TABLE pull_requests (
    pull_request_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repository_id BIGINT NOT NULL REFERENCES repositories(repository_id)
        ON DELETE CASCADE,
    pull_request_number INTEGER NOT NULL,
    author_id BIGINT NOT NULL REFERENCES repository_users(user_id),
    source_branch_id BIGINT NOT NULL REFERENCES branches(branch_id),
    target_branch_id BIGINT NOT NULL REFERENCES branches(branch_id),
    title TEXT NOT NULL,
    description TEXT NOT NULL DEFAULT '',
    state TEXT NOT NULL DEFAULT 'open'
        CHECK (state IN ('draft', 'open', 'closed', 'merged')),
    is_draft BOOLEAN NOT NULL DEFAULT FALSE,
    base_sha TEXT NOT NULL,
    source_head_sha TEXT NOT NULL,
    merge_sha TEXT,
    merge_strategy TEXT
        CHECK (merge_strategy IN ('merge_commit', 'squash', 'rebase')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    closed_at TIMESTAMPTZ,
    merged_at TIMESTAMPTZ,
    UNIQUE (repository_id, pull_request_number),
    CHECK (pull_request_number > 0),
    CHECK (length(title) BETWEEN 5 AND 120),
    CHECK (source_branch_id <> target_branch_id),
    CHECK (base_sha ~ '^[a-f0-9]{7,40}$'),
    CHECK (source_head_sha ~ '^[a-f0-9]{7,40}$'),
    CHECK (merge_sha IS NULL OR merge_sha ~ '^[a-f0-9]{7,40}$'),
    CHECK (
        (state = 'merged' AND merge_sha IS NOT NULL AND merged_at IS NOT NULL)
        OR
        (state <> 'merged' AND merge_sha IS NULL AND merged_at IS NULL)
    ),
    CHECK (NOT is_draft OR state IN ('draft', 'closed'))
);

CREATE TABLE pull_request_commits (
    pull_request_id BIGINT NOT NULL REFERENCES pull_requests(pull_request_id)
        ON DELETE CASCADE,
    commit_id BIGINT NOT NULL REFERENCES commits(commit_id),
    position INTEGER NOT NULL,
    PRIMARY KEY (pull_request_id, commit_id),
    UNIQUE (pull_request_id, position),
    CHECK (position > 0)
);

CREATE TABLE code_owners (
    repository_id BIGINT NOT NULL REFERENCES repositories(repository_id)
        ON DELETE CASCADE,
    path_pattern TEXT NOT NULL,
    owner_id BIGINT NOT NULL REFERENCES repository_users(user_id),
    PRIMARY KEY (repository_id, path_pattern, owner_id),
    CHECK (path_pattern <> '')
);

CREATE TABLE branch_protection_policies (
    policy_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repository_id BIGINT NOT NULL REFERENCES repositories(repository_id)
        ON DELETE CASCADE,
    branch_pattern TEXT NOT NULL,
    required_approvals INTEGER NOT NULL DEFAULT 1,
    require_resolved_conversations BOOLEAN NOT NULL DEFAULT TRUE,
    require_linear_history BOOLEAN NOT NULL DEFAULT FALSE,
    restrict_direct_pushes BOOLEAN NOT NULL DEFAULT TRUE,
    prohibit_force_pushes BOOLEAN NOT NULL DEFAULT TRUE,
    prohibit_deletion BOOLEAN NOT NULL DEFAULT TRUE,
    dismiss_stale_approvals BOOLEAN NOT NULL DEFAULT TRUE,
    require_code_owner_approval BOOLEAN NOT NULL DEFAULT FALSE,
    enforce_for_administrators BOOLEAN NOT NULL DEFAULT TRUE,
    allow_bypass BOOLEAN NOT NULL DEFAULT FALSE,
    UNIQUE (repository_id, branch_pattern),
    CHECK (branch_pattern <> ''),
    CHECK (required_approvals BETWEEN 0 AND 100)
);

CREATE TABLE policy_required_checks (
    policy_id BIGINT NOT NULL REFERENCES branch_protection_policies(policy_id)
        ON DELETE CASCADE,
    check_name TEXT NOT NULL,
    PRIMARY KEY (policy_id, check_name),
    CHECK (check_name <> '')
);

CREATE TABLE eligible_reviewers (
    policy_id BIGINT NOT NULL REFERENCES branch_protection_policies(policy_id)
        ON DELETE CASCADE,
    reviewer_id BIGINT NOT NULL REFERENCES repository_users(user_id),
    PRIMARY KEY (policy_id, reviewer_id)
);

CREATE TABLE reviews (
    review_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pull_request_id BIGINT NOT NULL REFERENCES pull_requests(pull_request_id)
        ON DELETE CASCADE,
    reviewer_id BIGINT NOT NULL REFERENCES repository_users(user_id),
    decision TEXT NOT NULL
        CHECK (decision IN (
            'approved', 'changes_requested', 'commented', 'dismissed'
        )),
    reviewed_commit_sha TEXT NOT NULL,
    submitted_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    dismissal_reason TEXT,
    CHECK (reviewed_commit_sha ~ '^[a-f0-9]{7,40}$'),
    CHECK (
        (decision = 'dismissed' AND dismissal_reason IS NOT NULL)
        OR decision <> 'dismissed'
    )
);

CREATE TABLE review_comments (
    comment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    review_id BIGINT NOT NULL REFERENCES reviews(review_id)
        ON DELETE CASCADE,
    file_path TEXT NOT NULL,
    line_number INTEGER NOT NULL,
    body TEXT NOT NULL,
    resolved BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    resolved_at TIMESTAMPTZ,
    CHECK (file_path <> ''),
    CHECK (line_number > 0),
    CHECK (body <> ''),
    CHECK (
        (resolved AND resolved_at IS NOT NULL)
        OR
        (NOT resolved AND resolved_at IS NULL)
    )
);

CREATE TABLE status_checks (
    status_check_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pull_request_id BIGINT NOT NULL REFERENCES pull_requests(pull_request_id)
        ON DELETE CASCADE,
    check_name TEXT NOT NULL,
    checked_commit_sha TEXT NOT NULL,
    status TEXT NOT NULL
        CHECK (status IN ('pending', 'success', 'failure', 'cancelled')),
    started_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at TIMESTAMPTZ,
    CHECK (check_name <> ''),
    CHECK (checked_commit_sha ~ '^[a-f0-9]{7,40}$'),
    CHECK (
        (status = 'pending' AND completed_at IS NULL)
        OR
        (status <> 'pending' AND completed_at IS NOT NULL)
    )
);

CREATE TABLE merge_audit (
    audit_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pull_request_id BIGINT NOT NULL REFERENCES pull_requests(pull_request_id),
    actor_id BIGINT NOT NULL REFERENCES repository_users(user_id),
    action TEXT NOT NULL
        CHECK (action IN ('opened', 'reopened', 'closed', 'merged', 'policy_bypass')),
    details JSONB NOT NULL DEFAULT '{}'::jsonb,
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_pull_requests_repository_state
    ON pull_requests(repository_id, state, updated_at DESC);

CREATE INDEX idx_reviews_pr_reviewer_time
    ON reviews(pull_request_id, reviewer_id, submitted_at DESC);

CREATE INDEX idx_comments_unresolved
    ON review_comments(review_id, created_at)
    WHERE resolved = FALSE;

CREATE INDEX idx_status_checks_latest
    ON status_checks(pull_request_id, check_name, started_at DESC);

CREATE INDEX idx_commits_repository_time
    ON commits(repository_id, committed_at DESC);

