-- Latest review state per reviewer is evaluated with DISTINCT ON.
-- Dismissed reviews are excluded from approval counts.
CREATE VIEW latest_reviewer_decisions AS
SELECT DISTINCT ON (r.pull_request_id, r.reviewer_id)
    r.pull_request_id,
    r.reviewer_id,
    r.decision,
    r.reviewed_commit_sha,
    r.submitted_at
FROM reviews r
ORDER BY r.pull_request_id, r.reviewer_id, r.submitted_at DESC, r.review_id DESC;

CREATE VIEW pull_request_merge_eligibility AS
WITH applicable_policy AS (
    SELECT
        pr.pull_request_id,
        pr.repository_id,
        pr.state,
        pr.is_draft,
        pr.source_branch_id,
        pr.target_branch_id,
        pr.source_head_sha,
        pr.base_sha,
        pr.title,
        bp.policy_id,
        bp.required_approvals,
        bp.require_resolved_conversations,
        bp.require_linear_history,
        bp.dismiss_stale_approvals,
        bp.require_code_owner_approval
    FROM pull_requests pr
    JOIN branches target
      ON target.branch_id = pr.target_branch_id
    JOIN branch_protection_policies bp
      ON bp.repository_id = pr.repository_id
     AND bp.branch_pattern = target.branch_name
),
approval_counts AS (
    SELECT
        p.pull_request_id,
        COUNT(*) FILTER (
            WHERE d.decision = 'approved'
              AND (
                  NOT p.dismiss_stale_approvals
                  OR d.reviewed_commit_sha = p.source_head_sha
              )
        ) AS valid_approvals,
        BOOL_OR(d.decision = 'changes_requested') AS changes_requested
    FROM applicable_policy p
    LEFT JOIN latest_reviewer_decisions d
      ON d.pull_request_id = p.pull_request_id
    GROUP BY p.pull_request_id
),
check_states AS (
    SELECT DISTINCT ON (sc.pull_request_id, sc.check_name)
        sc.pull_request_id,
        sc.check_name,
        sc.status,
        sc.checked_commit_sha
    FROM status_checks sc
    ORDER BY sc.pull_request_id, sc.check_name, sc.started_at DESC,
             sc.status_check_id DESC
),
check_compliance AS (
    SELECT
        p.pull_request_id,
        COUNT(*) FILTER (
            WHERE cs.status = 'success'
              AND cs.checked_commit_sha = p.source_head_sha
        ) AS passing_required_checks,
        COUNT(prc.check_name) AS required_check_count
    FROM applicable_policy p
    JOIN policy_required_checks prc
      ON prc.policy_id = p.policy_id
    LEFT JOIN check_states cs
      ON cs.pull_request_id = p.pull_request_id
     AND cs.check_name = prc.check_name
    GROUP BY p.pull_request_id
),
conversation_compliance AS (
    SELECT
        p.pull_request_id,
        COUNT(rc.comment_id) FILTER (WHERE NOT rc.resolved) AS unresolved_comments
    FROM applicable_policy p
    LEFT JOIN reviews r ON r.pull_request_id = p.pull_request_id
    LEFT JOIN review_comments rc ON rc.review_id = r.review_id
    GROUP BY p.pull_request_id
)
SELECT
    p.pull_request_id,
    p.repository_id,
    p.title,
    p.state,
    COALESCE(a.valid_approvals, 0) AS valid_approvals,
    p.required_approvals,
    COALESCE(c.passing_required_checks, 0) AS passing_required_checks,
    COALESCE(c.required_check_count, 0) AS required_check_count,
    COALESCE(a.changes_requested, FALSE) AS changes_requested,
    COALESCE(cc.unresolved_comments, 0) AS unresolved_comments,
    (
        p.state = 'open'
        AND NOT p.is_draft
        AND p.source_branch_id <> p.target_branch_id
        AND COALESCE(a.valid_approvals, 0) >= p.required_approvals
        AND NOT COALESCE(a.changes_requested, FALSE)
        AND COALESCE(c.passing_required_checks, 0) =
            COALESCE(c.required_check_count, 0)
        AND (
            NOT p.require_resolved_conversations
            OR COALESCE(cc.unresolved_comments, 0) = 0
        )
    ) AS preliminarily_eligible
FROM applicable_policy p
LEFT JOIN approval_counts a ON a.pull_request_id = p.pull_request_id
LEFT JOIN check_compliance c ON c.pull_request_id = p.pull_request_id
LEFT JOIN conversation_compliance cc ON cc.pull_request_id = p.pull_request_id;

-- Eligibility results expose the individual causes of a blocked merge.
SELECT
    pull_request_id,
    title,
    state,
    valid_approvals,
    required_approvals,
    passing_required_checks,
    required_check_count,
    changes_requested,
    unresolved_comments,
    preliminarily_eligible
FROM pull_request_merge_eligibility
ORDER BY pull_request_id;

-- Detailed policy diagnostics identify missing, failed, stale, or pending checks.
SELECT
    pr.pull_request_number,
    required.check_name,
    COALESCE(latest.status, 'missing') AS latest_status,
    CASE
        WHEN latest.status IS NULL THEN 'missing check'
        WHEN latest.checked_commit_sha <> pr.source_head_sha THEN 'stale check'
        WHEN latest.status <> 'success' THEN 'check not successful'
        ELSE 'passing'
    END AS diagnostic
FROM pull_requests pr
JOIN branches target ON target.branch_id = pr.target_branch_id
JOIN branch_protection_policies bp
  ON bp.repository_id = pr.repository_id
 AND bp.branch_pattern = target.branch_name
JOIN policy_required_checks required ON required.policy_id = bp.policy_id
LEFT JOIN LATERAL (
    SELECT sc.status, sc.checked_commit_sha
    FROM status_checks sc
    WHERE sc.pull_request_id = pr.pull_request_id
      AND sc.check_name = required.check_name
    ORDER BY sc.started_at DESC, sc.status_check_id DESC
    LIMIT 1
) latest ON TRUE
ORDER BY pr.pull_request_number, required.check_name;

-- A transaction records a close event without deleting review history.
WITH changed AS (
    UPDATE pull_requests
       SET state = 'closed',
           is_draft = FALSE,
           closed_at = CURRENT_TIMESTAMP,
           updated_at = CURRENT_TIMESTAMP
     WHERE pull_request_id = 3
       AND state = 'draft'
    RETURNING pull_request_id, author_id
)
INSERT INTO merge_audit (pull_request_id, actor_id, action, details)
SELECT pull_request_id, author_id, 'closed',
       '{"reason":"draft abandoned"}'::jsonb
FROM changed;

