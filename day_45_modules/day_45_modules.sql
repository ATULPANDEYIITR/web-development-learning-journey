-- PostgreSQL 15+ compatible ES module architecture catalog.
-- Models module contracts, named/default exports, imports, dependency layers,
-- dependency validation, cycle detection, and dependency-first build planning.

BEGIN;

DROP VIEW IF EXISTS module_dependency_report CASCADE;
DROP TABLE IF EXISTS module_validation_errors CASCADE;
DROP TABLE IF EXISTS module_dependencies CASCADE;
DROP TABLE IF EXISTS module_imports CASCADE;
DROP TABLE IF EXISTS module_exports CASCADE;
DROP TABLE IF EXISTS source_modules CASCADE;

CREATE TABLE source_modules (
    module_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    module_path TEXT NOT NULL UNIQUE,
    architecture_layer TEXT NOT NULL CHECK (
        architecture_layer IN (
            'domain',
            'application',
            'infrastructure',
            'presentation'
        )
    ),
    module_status TEXT NOT NULL DEFAULT 'registered' CHECK (
        module_status IN ('registered', 'validated', 'failed')
    ),
    source_hash TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (module_path <> ''),
    CHECK (module_path NOT LIKE '/%'),
    CHECK (module_path NOT LIKE '%..%')
);

CREATE TABLE module_exports (
    export_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    module_id BIGINT NOT NULL REFERENCES source_modules(module_id)
        ON DELETE CASCADE,
    export_name TEXT NOT NULL,
    export_kind TEXT NOT NULL CHECK (export_kind IN ('named', 'default')),
    CHECK (
        (export_kind = 'default' AND export_name = 'default')
        OR
        (export_kind = 'named' AND export_name <> 'default'
         AND export_name <> '')
    ),
    UNIQUE (module_id, export_name),
    UNIQUE (module_id, export_kind, export_name)
);

-- One row describes a static import binding. imported_name='default' and
-- import_kind='default' distinguish a default import from a named import.
CREATE TABLE module_imports (
    import_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    importer_id BIGINT NOT NULL REFERENCES source_modules(module_id)
        ON DELETE CASCADE,
    specifier TEXT NOT NULL,
    imported_name TEXT NOT NULL,
    local_name TEXT NOT NULL,
    import_kind TEXT NOT NULL CHECK (
        import_kind IN ('named', 'default', 'namespace', 'side_effect')
    ),
    resolved_module_id BIGINT REFERENCES source_modules(module_id)
        ON DELETE RESTRICT,
    CHECK (specifier <> ''),
    CHECK (local_name <> ''),
    CHECK (
        (import_kind = 'default' AND imported_name = 'default')
        OR import_kind <> 'default'
    )
);

CREATE INDEX module_imports_importer_idx
    ON module_imports(importer_id);

CREATE INDEX module_imports_resolved_idx
    ON module_imports(resolved_module_id);

CREATE TABLE module_dependencies (
    importer_id BIGINT NOT NULL REFERENCES source_modules(module_id)
        ON DELETE CASCADE,
    dependency_id BIGINT NOT NULL REFERENCES source_modules(module_id)
        ON DELETE CASCADE,
    PRIMARY KEY (importer_id, dependency_id),
    CHECK (importer_id <> dependency_id)
);

CREATE INDEX module_dependencies_target_idx
    ON module_dependencies(dependency_id);

CREATE TABLE module_validation_errors (
    error_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    importer_id BIGINT REFERENCES source_modules(module_id)
        ON DELETE CASCADE,
    import_id BIGINT REFERENCES module_imports(import_id)
        ON DELETE CASCADE,
    error_code TEXT NOT NULL CHECK (
        error_code IN (
            'unresolved_import',
            'missing_export',
            'forbidden_layer_dependency',
            'circular_dependency'
        )
    ),
    details TEXT NOT NULL,
    detected_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE VIEW module_dependency_report AS
SELECT
    m.module_path,
    m.architecture_layer,
    m.module_status,
    COALESCE(
        array_agg(d.module_path ORDER BY d.module_path)
            FILTER (WHERE d.module_id IS NOT NULL),
        ARRAY[]::TEXT[]
    ) AS dependencies,
    count(e.export_id) FILTER (WHERE e.export_kind = 'named')
        AS named_export_count,
    bool_or(e.export_kind = 'default') AS has_default_export
FROM source_modules AS m
LEFT JOIN module_dependencies AS md
    ON md.importer_id = m.module_id
LEFT JOIN source_modules AS d
    ON d.module_id = md.dependency_id
LEFT JOIN module_exports AS e
    ON e.module_id = m.module_id
GROUP BY m.module_id, m.module_path, m.architecture_layer, m.module_status;

