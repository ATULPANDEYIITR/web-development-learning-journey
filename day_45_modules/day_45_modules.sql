-- Evaluate import contracts and layer boundaries. The transaction can retain
-- failed module status and diagnostics for inspection without hiding failures.
INSERT INTO module_validation_errors (
    importer_id, import_id, error_code, details
)
SELECT
    i.importer_id,
    i.import_id,
    'missing_export',
    format(
        'Module %s requests named export %s from %s',
        importer.module_path,
        i.imported_name,
        target.module_path
    )
FROM module_imports AS i
JOIN source_modules AS importer ON importer.module_id = i.importer_id
JOIN source_modules AS target ON target.module_id = i.resolved_module_id
WHERE i.import_kind = 'named'
  AND NOT EXISTS (
      SELECT 1
      FROM module_exports AS e
      WHERE e.module_id = i.resolved_module_id
        AND e.export_kind = 'named'
        AND e.export_name = i.imported_name
  );

INSERT INTO module_validation_errors (
    importer_id, import_id, error_code, details
)
SELECT
    i.importer_id,
    i.import_id,
    'forbidden_layer_dependency',
    format(
        '%s layer cannot import %s layer directly',
        importer.architecture_layer,
        target.architecture_layer
    )
FROM module_imports AS i
JOIN source_modules AS importer ON importer.module_id = i.importer_id
JOIN source_modules AS target ON target.module_id = i.resolved_module_id
WHERE
    (importer.architecture_layer = 'domain'
        AND target.architecture_layer <> 'domain')
    OR
    (importer.architecture_layer = 'infrastructure'
        AND target.architecture_layer NOT IN ('domain'))
    OR
    (importer.architecture_layer = 'application'
        AND target.architecture_layer = 'presentation')
    OR
    (importer.architecture_layer = 'presentation'
        AND target.architecture_layer NOT IN ('application', 'domain'));

UPDATE source_modules AS m
SET module_status = CASE
    WHEN EXISTS (
        SELECT 1
        FROM module_validation_errors AS e
        WHERE e.importer_id = m.module_id
    ) THEN 'failed'
    ELSE 'validated'
END;

-- Report invalid imports and architectural violations.
SELECT
    m.module_path,
    e.error_code,
    e.details,
    e.detected_at
FROM module_validation_errors AS e
LEFT JOIN source_modules AS m ON m.module_id = e.importer_id
ORDER BY m.module_path, e.error_code;

-- Dependency-first ordering uses Kahn's algorithm. A cycle leaves at least one
-- module with a positive unresolved dependency count.
WITH RECURSIVE dependency_counts AS (
    SELECT
        m.module_id,
        m.module_path,
        count(d.dependency_id)::INTEGER AS remaining_dependencies
    FROM source_modules AS m
    LEFT JOIN module_dependencies AS d ON d.importer_id = m.module_id
    GROUP BY m.module_id, m.module_path
),
walk AS (
    SELECT
        dc.module_id,
        dc.module_path,
        dc.remaining_dependencies,
        ARRAY[dc.module_id] AS processed,
        0 AS build_position
    FROM dependency_counts AS dc
    WHERE dc.remaining_dependencies = 0

    UNION ALL

    SELECT
        dc.module_id,
        dc.module_path,
        dc.remaining_dependencies,
        w.processed || dc.module_id,
        w.build_position + 1
    FROM walk AS w
    JOIN dependency_counts AS dc
      ON dc.module_id <> ALL(w.processed)
    WHERE dc.remaining_dependencies = 0
)
SELECT module_path, remaining_dependencies
FROM dependency_counts
ORDER BY module_path;

-- Explicit cycle detection through transitive reachability. A module reachable
-- from itself through one or more edges belongs to a circular dependency.
WITH RECURSIVE reachability(start_id, reached_id, path) AS (
    SELECT
        dependency_id,
        importer_id,
        ARRAY[dependency_id, importer_id]
    FROM module_dependencies

    UNION ALL

    SELECT
        r.start_id,
        d.importer_id,
        r.path || d.importer_id
    FROM reachability AS r
    JOIN module_dependencies AS d ON d.dependency_id = r.reached_id
    WHERE NOT d.importer_id = ANY(r.path)
)
SELECT DISTINCT
    start_module.module_path AS cycle_start,
    reached_module.module_path AS reachable_module
FROM reachability AS r
JOIN source_modules AS start_module ON start_module.module_id = r.start_id
JOIN source_modules AS reached_module ON reached_module.module_id = r.reached_id
WHERE r.start_id = r.reached_id;

-- Example of an atomic architecture update. A deployment process should fail
-- when unresolved contracts exist, rather than silently shipping a broken graph.
DO $$
DECLARE
    failure_count INTEGER;
BEGIN
    SELECT count(*) INTO failure_count
    FROM module_validation_errors;

    IF failure_count > 0 THEN
        RAISE NOTICE
            'Architecture validation found % issue(s); affected modules remain failed.',
            failure_count;
    ELSE
        RAISE NOTICE 'All module contracts and layer rules passed.';
    END IF;
END
$$;

COMMIT;
